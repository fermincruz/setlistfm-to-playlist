export const LANGUAGES = Object.keys(messages);

export function detectLanguage(preferred, navigatorLanguages = []) {
  if (LANGUAGES.includes(preferred)) return preferred;
  for (const lang of navigatorLanguages) {
    const short = String(lang).slice(0, 2).toLowerCase();
    if (LANGUAGES.includes(short)) return short;
  }
  return 'es';
}

export function createTranslator(lang) {
  const dict = messages[lang] ?? messages.es;
  const fill = (text, vars) => String(text).replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
  const t = (key, vars = {}) => fill(dict[key] ?? messages.es[key] ?? key, vars);
  t.error = (error) => {
    const code = error?.code ?? 'unknown';
    const text = dict.errors[code] ?? dict.errors.unknown;
    return fill(text, { status: error?.status || '?' });
  };
  t.lang = lang;
  t.locale = lang === 'es' ? 'es-ES' : 'en-GB';
  return t;
}
